// The shared conformance corpus on the web target.
//
//   dart run tool/web_conformance.dart
//
// STANDARD.md, "Wide integers are exact": a runtime whose ordinary number is
// a double must still carry 64-bit and 128-bit values as integers, bit for
// bit. On the web this library has two compilers, and this tool holds both to
// that rule:
//
//  - dart2wasm keeps Dart's int a 64-bit integer, so the library runs there
//    unchanged. The tool builds the conformance runner for it with the whole
//    vendored corpus embedded (the web has no file system to read it from),
//    runs it under Node, and requires every vector to pass: the same corpus,
//    the same runner, the same refusal reasons as on the VM.
//
//  - dart2js makes Dart's int a JavaScript double, which would round 2^53 + 1
//    and everything past it. The library does not compile there: dart2js
//    refuses the literal 2^63 - 1, the web guard `int64Max` in
//    lib/src/bits.dart. The tool requires that refusal, by the guard's file
//    and literal rather than by the compiler's wording, so a change that let
//    the library build for dart2js, and so round wide values in silence,
//    turns this red, and a reworded compiler message does not.
//
// Everything it writes goes under .dart_tool/web_conformance/.

import 'dart:convert';
import 'dart:io';

/// Where the web guard lives, and its literal: dart2js must refuse there.
const String _guardFile = 'lib/src/bits.dart';
const String _guardLiteral = '0x7FFFFFFFFFFFFFFF';

String _entry(Map<String, String> corpus) {
  final buffer = StringBuffer()
    ..writeln('// GENERATED by tool/web_conformance.dart. Do not edit.')
    ..writeln()
    ..writeln("import '../../test/conformance_runner.dart';")
    ..writeln("import '../../test/harness.dart';")
    ..writeln()
    ..writeln('const Map<String, String> _corpus = {');
  corpus.forEach((path, text) {
    // a JSON string is a Dart string literal once its dollars are escaped
    String literal(String s) => jsonEncode(s).replaceAll(r'$', r'\$');
    buffer.writeln('  ${literal(path)}: ${literal(text)},');
  });
  buffer
    ..writeln('};')
    ..writeln()
    ..writeln('void main() {')
    ..writeln('  for (final entry in _corpus.entries) {')
    ..writeln(r"    test('conformance: ${entry.key}', () {")
    ..writeln('      if (runVectorFile(entry.key, entry.value) == 0) {')
    ..writeln(r"        failUnowned('${entry.key} holds no vectors');")
    ..writeln('      }')
    ..writeln('    });')
    ..writeln('  }')
    ..writeln(r"  print('web (dart2wasm): ${corpusSummary(_corpus.length)}');")
    ..writeln('  if (vectorsChecked == 0 || summarize() > 0) {')
    ..writeln("    throw StateError('the corpus failed on the web target');")
    ..writeln('  }')
    ..writeln('}');
  return buffer.toString();
}

const String _node = '''
import { readFileSync } from 'node:fs';
const [, , mjs, wasm] = process.argv;
const module = await import(mjs);
const instance = await (await module.compile(readFileSync(wasm))).instantiate({});
instance.invokeMain();
''';

Future<int> _run(String executable, List<String> args, String cwd) async {
  final process = await Process.start(
    executable,
    args,
    workingDirectory: cwd,
    mode: ProcessStartMode.inheritStdio,
  );
  return process.exitCode;
}

Future<void> main() async {
  final root = File.fromUri(Platform.script).parent.parent.absolute.path;
  final work = Directory('$root/.dart_tool/web_conformance');
  if (work.existsSync()) {
    work.deleteSync(recursive: true);
  }
  work.createSync(recursive: true);

  // the corpus directory is enumerated, never named file by file
  final files =
      Directory('$root/conformance')
          .listSync()
          .whereType<File>()
          .where((f) => f.path.endsWith('.txt'))
          .toList()
        ..sort((a, b) => a.path.compareTo(b.path));
  if (files.isEmpty) {
    stderr.writeln('web conformance: conformance/ holds no vector files');
    exit(1);
  }
  final corpus = {
    for (final file in files)
      'conformance/${file.uri.pathSegments.last}': file.readAsStringSync(),
  };
  final entry = File('${work.path}/main.dart')
    ..writeAsStringSync(_entry(corpus));
  File('${work.path}/run.mjs').writeAsStringSync(_node);

  final dart = Platform.resolvedExecutable;
  var failed = false;

  // dart2wasm: build, then run the corpus under Node
  if (await _run(dart, [
        'compile',
        'wasm',
        '-o',
        '${work.path}/main.wasm',
        entry.path,
      ], root) !=
      0) {
    stderr.writeln('web conformance: dart2wasm could not build the runner');
    failed = true;
  } else if (await _run('node', [
        '${work.path}/run.mjs',
        '${work.path}/main.mjs',
        '${work.path}/main.wasm',
      ], root) !=
      0) {
    stderr.writeln('web conformance: the corpus failed under dart2wasm');
    failed = true;
  }

  // dart2js: the build must be refused, for the reason that keeps a 64-bit
  // value out of a JavaScript double
  final js = await Process.run(dart, [
    'compile',
    'js',
    '-o',
    '${work.path}/main.js',
    entry.path,
  ], workingDirectory: root);
  final output = '${js.stdout}${js.stderr}';
  if (js.exitCode == 0) {
    stderr.writeln(
      'web conformance: dart2js BUILT the library, whose int is a JavaScript '
      'double there: 64-bit values would round in silence',
    );
    failed = true;
  } else if (!output.contains(_guardFile) || !output.contains(_guardLiteral)) {
    stderr.writeln(
      'web conformance: dart2js failed, but not by refusing the web guard '
      '$_guardLiteral in $_guardFile:\n$output',
    );
    failed = true;
  } else {
    print(
      'web (dart2js): refused to build at the web guard in $_guardFile, so '
      'no 64-bit value reaches a JavaScript double',
    );
  }

  // the control: a copy of the library whose guard is computed rather than a
  // literal must BUILD under dart2js, which the check above would turn red.
  // A gate nobody has seen go red is a claim, not a measurement
  final control = Directory('${work.path}/control')..createSync();
  _copyTree(Directory('$root/lib'), Directory('${control.path}/lib'));
  final guard = File('${control.path}/$_guardFile');
  final guarded = guard.readAsStringSync();
  final unguarded = guarded.replaceFirst(
    'int64Max = $_guardLiteral;',
    'int64Max = (1 << 62) - 1 + (1 << 62);',
  );
  if (unguarded == guarded) {
    stderr.writeln('web conformance: control: no guard to remove');
    failed = true;
  } else {
    guard.writeAsStringSync(unguarded);
    final controlEntry = File('${control.path}/main.dart')
      ..writeAsStringSync(
        "import 'lib/serialize.dart';\n\n"
        'void main() => print(WriteStream);\n',
      );
    final built = await Process.run(dart, [
      'compile',
      'js',
      '-o',
      '${control.path}/main.js',
      controlEntry.path,
    ], workingDirectory: root);
    if (built.exitCode != 0) {
      stderr.writeln(
        'web conformance: control: without the guard dart2js still refused, '
        'so the gate cannot tell the guard did the refusing:\n'
        '${built.stdout}${built.stderr}',
      );
      failed = true;
    } else {
      print('web (dart2js) control: without the guard the library builds');
    }
  }

  exit(failed ? 1 : 0);
}

void _copyTree(Directory from, Directory to) {
  to.createSync(recursive: true);
  for (final entity in from.listSync()) {
    final name = entity.uri.pathSegments.lastWhere((s) => s.isNotEmpty);
    if (entity is Directory) {
      _copyTree(entity, Directory('${to.path}/$name'));
    } else if (entity is File) {
      entity.copySync('${to.path}/$name');
    }
  }
}
